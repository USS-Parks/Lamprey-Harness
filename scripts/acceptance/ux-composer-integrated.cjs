/* global window, document, getComputedStyle */
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
module.exports = async function integratedComposer({ page, app, ids, profile, repo, providerBodies, output }) {
  const input = page.getByRole('textbox', { name: 'Message Lamprey', exact: true })
  const send = page.getByRole('button', { name: 'Send', exact: true })
  const stop = page.getByRole('button', { name: 'Stop current turn', exact: true })
  const select = async id => {
    const expand = page.getByRole('button', { name: 'Expand sidebar', exact: true })
    if (await expand.isVisible()) await expand.click()
    const title = await page.evaluate(async id => (await window.api.conversation.list()).data.find(task => task.id === id).title, id)
    await page.getByText(title, { exact: true }).last().click()
    await input.waitFor()
    await page.waitForFunction(() => !document.querySelector('textarea[aria-label="Message Lamprey"]').disabled)
  }
  await select(ids[1])
  await input.fill('Draft owned by task one')
  await select(ids[2])
  assert.equal(await input.inputValue(), '', 'Switching tasks must not migrate a draft')
  await input.fill('Draft owned by task two')
  await select(ids[1])
  assert.equal(await input.inputValue(), 'Draft owned by task one')
  await page.reload()
  await select(ids[2])
  assert.equal(await input.inputValue(), 'Draft owned by task two')
  await select(ids[1])
  const note = path.join(profile, 'integrated-note.txt')
  const image = path.join(profile, 'integrated-image.png')
  fs.writeFileSync(note, 'Text after the image in the normal message.')
  fs.writeFileSync(image, Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64'))
  await app.evaluate(({ dialog }, files) => {
    dialog.showOpenDialog = async () => {
      await new Promise(resolve => { globalThis.uxReleasePicker = resolve })
      return { canceled: false, filePaths: files }
    }
  }, [image, note])
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('button', { name: /Add files or photos/ }).click()
  await app.evaluate(async () => {
    for (let i = 0; i < 100 && !globalThis.uxReleasePicker; i++) await new Promise(resolve => setTimeout(resolve, 20))
    if (!globalThis.uxReleasePicker) throw new Error('Picker was not reached')
  })
  await select(ids[2])
  await app.evaluate(() => { globalThis.uxReleasePicker(); delete globalThis.uxReleasePicker })
  await page.waitForFunction(async id => (await window.api.conversation.getDraft(id)).data.attachments.length === 2, ids[1])
  assert.equal(await page.getByTitle('Remove attachment', { exact: true }).count(), 0)
  assert.equal(await input.inputValue(), 'Draft owned by task two')
  await select(ids[1])
  await page.getByText('integrated-note.txt', { exact: true }).waitFor()
  await page.reload()
  await select(ids[1])
  assert.equal(await page.getByTitle('Remove attachment', { exact: true }).count(), 2)
  await page.getByTitle('Switch model', { exact: true }).click()
  const menu = page.getByRole('menu', { name: 'Models', exact: true })
  await menu.getByRole('searchbox', { name: 'Search models', exact: true }).fill('fixture-vision')
  await menu.locator('[data-model-id="fixture-vision"]').click()
  const count = () => page.evaluate(async id => (await window.api.conversation.getMessages(id)).data.filter(message => message.role === 'user').length, ids[1])
  const before = await count()
  for (const mode of ['reject', 'throw']) {
    await app.evaluate(({ ipcMain }, mode) => {
      const original = ipcMain._invokeHandlers.get('chat:send')
      ipcMain.removeHandler('chat:send')
      ipcMain.handle('chat:send', async () => {
        ipcMain.removeHandler('chat:send'); ipcMain.handle('chat:send', original)
        if (mode === 'throw') throw new Error('UX normal send transport failure')
        return { success: false, error: 'UX normal send rejected' }
      })
    }, mode)
    await send.click()
    await page.getByText(mode === 'reject' ? 'UX normal send rejected' : /UX normal send transport failure/).first().waitFor()
    await send.waitFor()
    assert.equal(await input.inputValue(), 'Draft owned by task one')
    assert.equal(await page.getByTitle('Remove attachment', { exact: true }).count(), 2)
    assert.equal(await count(), before)
  }
  await input.fill('UX16 ordered normal image request')
  await send.evaluate(button => { button.click(); button.click() })
  await stop.waitFor()
  for (let i = 0; i < 100 && !providerBodies.some(body => body.model === 'fixture-vision'); i++) await new Promise(resolve => setTimeout(resolve, 50))
  const request = providerBodies.find(body => body.model === 'fixture-vision')
  assert(request)
  const user = request.messages.find(message => message.role === 'user' && Array.isArray(message.content) && message.content.some(item => item.type === 'text' && item.text.includes('UX16 ordered')))
  assert(user, 'Actual provider request contains structured user input')
  assert.deepEqual(user.content.map(item => item.type), ['text', 'image_url', 'text'])
  assert(user.content[2].text.includes('Text after the image'))
  assert.equal(await count(), before + 1)
  assert.equal(await input.inputValue(), '')
  assert.equal(await page.getByTitle('Remove attachment', { exact: true }).count(), 0)
  await input.fill('New draft while this task runs')
  await select(ids[2])
  assert.equal(await stop.count(), 0)
  assert.equal(await input.inputValue(), 'Draft owned by task two')
  assert((await page.evaluate(async id => (await window.api.turn.getState(id)).data.activeTurn, ids[1])))
  await select(ids[1])
  assert.equal(await input.inputValue(), 'New draft while this task runs')
  await page.getByRole('button', { name: 'Choose Steer or Queue', exact: true }).click()
  await page.locator('[data-follow-up-choice="queue"]').click()
  await input.fill('UX16 queued using Enter')
  await input.press('Enter')
  const queued = page.getByRole('article', { name: 'Queued follow-up', exact: true }).filter({ hasText: 'UX16 queued using Enter' })
  await queued.waitFor()
  await queued.getByRole('button', { name: 'Delete', exact: true }).click()
  await stop.click()
  await send.waitFor()
  await page.reload()
  await select(ids[1])
  await input.fill('UX16 verify image history after reload')
  const requestCount = providerBodies.length
  await send.click()
  await stop.waitFor()
  for (let i = 0; i < 100 && providerBodies.length === requestCount; i++) await new Promise(resolve => setTimeout(resolve, 50))
  const historyRequest = providerBodies.slice(requestCount).find(body => body.model === 'fixture-vision')
  assert(historyRequest.messages.some(message => message.role === 'user' && Array.isArray(message.content) && message.content.some(item => item.type === 'image_url')), 'Prior image survives renderer reload and next turn history')
  await stop.click()
  await send.waitFor()
  await input.fill('UX16 approval fixture')
  await send.click()
  const approval = page.getByRole('dialog', { name: 'Allow this action?', exact: true })
  await approval.waitFor()
  assert.equal(fs.existsSync(path.join(repo, 'ux16-approved.txt')), false, 'Tool must not mutate before approval')
  await approval.getByRole('button', { name: 'Allow', exact: true }).click()
  for (let i = 0; i < 150 && !fs.existsSync(path.join(repo, 'ux16-approved.txt')); i++) await new Promise(resolve => setTimeout(resolve, 50))
  assert.match(fs.readFileSync(path.join(repo, 'ux16-approved.txt'), 'utf8'), /Approved fixture write/)
  await input.fill('Draft retained through approval interruption')
  const layouts = []
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const [width, height, zoom, theme] of [[1440, 900, 1, 'Dark'], [1024, 768, 1.5, 'Dark'], [800, 600, 2, 'Dark'], [1440, 900, 1, 'Light'], [1024, 768, 1.5, 'Light'], [800, 600, 2, 'Light']]) {
    await app.evaluate(({ BrowserWindow }, { width, height, zoom }) => {
      const win = BrowserWindow.getAllWindows().find(window => window.webContents.getURL().includes('index.html'))
      win.setMinimumSize(400, 300); win.setContentSize(width, height); win.webContents.setZoomFactor(zoom)
    }, { width, height, zoom })
    if (width === 1440) {
      await page.getByRole('button', { name: 'Settings', exact: true }).first().click()
      const settings = page.getByRole('dialog', { name: 'Settings', exact: true })
      await settings.getByRole('tab', { name: 'Appearance', exact: true }).click()
      await settings.getByRole('button', { name: theme, exact: true }).click()
      await settings.getByRole('button', { name: 'Close settings', exact: true }).click()
    }
    await page.waitForTimeout(250)
    const drawer = page.getByRole('dialog', { name: 'Workspace panel', exact: true })
    if (await drawer.isVisible()) await drawer.getByRole('button', { name: 'Collapse panel', exact: true }).click()
    const navigation = page.getByRole('dialog', { name: 'Navigation', exact: true })
    if (await navigation.isVisible()) await navigation.getByRole('button', { name: 'Collapse sidebar', exact: true }).click()
    await input.click()
    await input.press('End')
    const geometry = await input.evaluate(node => { const box = node.getBoundingClientRect(); return { x: box.x, right: box.right, bottom: box.bottom, width: box.width, viewWidth: window.innerWidth, viewHeight: window.innerHeight, focused: node === document.activeElement } })
    assert(geometry.focused && geometry.width >= 100 && geometry.x >= 0 && geometry.right <= geometry.viewWidth + 1 && geometry.bottom <= geometry.viewHeight + 1, JSON.stringify(geometry))
    const stopBox = await stop.evaluate(node => { const box = node.getBoundingClientRect(); return { x: box.x, y: box.y, width: box.width, height: box.height } })
    assert(stopBox && stopBox.x >= 0 && stopBox.y >= 0 && stopBox.x + stopBox.width <= geometry.viewWidth + 1 && stopBox.y + stopBox.height <= geometry.viewHeight + 1, `Stop stays visible at every composer scale: ${JSON.stringify({ stopBox, geometry, width, height, zoom })}`)
    assert(await stop.evaluate(node => {
      const box = node.getBoundingClientRect()
      for (let parent = node.parentElement; parent; parent = parent.parentElement) {
        if (!['auto', 'scroll', 'hidden', 'clip'].includes(getComputedStyle(parent).overflowY)) continue
        const bounds = parent.getBoundingClientRect()
        if (box.top < bounds.top - 1 || box.bottom > bounds.bottom + 1) return false
      }
      return true
    }), 'The whole Stop target must be inside every clipping ancestor')
    assert.equal(await input.inputValue(), 'Draft retained through approval interruption')
    layouts.push({ width, height, zoom, theme, geometry, stopBox })
    const capture = await app.evaluate(async ({ BrowserWindow }) => (await BrowserWindow.getAllWindows().find(window => window.webContents.getURL().includes('index.html')).webContents.capturePage()).toPNG().toString('base64'))
    fs.writeFileSync(path.join(output, `COMPOSER_${width}_${zoom}_${theme}.png`), Buffer.from(capture, 'base64'))
  }
  await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows().find(window => window.webContents.getURL().includes('index.html')); win.webContents.setZoomFactor(1); win.setContentSize(1440, 900) })
  await stop.click()
  await send.waitFor()
  await input.fill('')
  const tasksBefore = await page.evaluate(async () => (await window.api.conversation.list()).data.map(task => task.id))
  await page.getByRole('button', { name: 'New task', exact: true }).first().click()
  await page.waitForFunction(() => !document.querySelector('textarea[aria-label="Message Lamprey"]').disabled)
  await input.fill('New task draft retained after rejected creation send')
  await app.evaluate(({ ipcMain }) => {
    const original = ipcMain._invokeHandlers.get('chat:send')
    ipcMain.removeHandler('chat:send')
    ipcMain.handle('chat:send', async () => {
      ipcMain.removeHandler('chat:send'); ipcMain.handle('chat:send', original)
      return { success: false, error: 'UX new task send rejected' }
    })
  })
  await send.evaluate(button => { button.click(); button.click() })
  await page.getByText('UX new task send rejected', { exact: true }).first().waitFor()
  const newTasks = await page.evaluate(async before => (await window.api.conversation.list()).data.filter(task => !before.includes(task.id)), tasksBefore)
  assert.equal(newTasks.length, 1, 'Initial double submit creates one task')
  assert.equal(await input.inputValue(), 'New task draft retained after rejected creation send')
  await page.reload()
  await select(newTasks[0].id)
  assert.equal(await input.inputValue(), 'New task draft retained after rejected creation send')
  fs.writeFileSync(path.join(output, 'COMPOSER_LAYOUTS.json'), JSON.stringify(layouts, null, 2) + '\n')
  return { taskDraftOwnership: true, reloadTextAndAttachments: true, delayedPickerOwnership: true, rejectedAndThrownNormalSendsRetainInput: true, synchronousDoubleSubmitOnce: true, orderedImageProviderDelivery: true, imageHistoryAfterReload: true, activeTaskSwitchAndStop: true, enterQueuesUsingVisiblePreference: true, realToolApprovalBeforeMutation: true, initialDoubleSubmitOnceAndRejectedDraftDurable: true, lightAndDark: true, narrowAnd200PercentStopVisible: true, boundary: 'Built renderer/preload/main, real SQLite and loopback provider. Only chooser and rejected IPC boundaries are controlled.' }
}
