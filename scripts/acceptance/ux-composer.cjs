/* global window, document, DataTransfer, ClipboardEvent, KeyboardEvent */
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

module.exports = async function composerScenario({ page, app, ids, profile, requestCount }) {
  const input = page.getByRole('textbox', { name: 'Message Lamprey', exact: true })
  const draft = 'Keep this draft.\nSecond line stays editable.'
  await input.fill(draft)
  const requestsBefore = requestCount()
  const settings = await page.evaluate(async () => (await window.api.settings.get()).data)
  const mode = page.getByRole('button', { name: 'Working mode', exact: true })
  for (const label of ['Auto Review', 'Full Access', 'Default permissions']) {
    await page.getByTitle('Permissions mode', { exact: true }).click()
    await page.locator('.chat-column').getByRole('button', { name: label, exact: true }).click()
    assert((await page.getByTitle('Permissions mode', { exact: true }).textContent()).includes(label))
    await mode.click()
    const menu = page.getByRole('menu', { name: 'Working mode', exact: true })
    const coding = menu.getByRole('button', { name: 'Coding', exact: true })
    const before = await coding.getAttribute('aria-pressed')
    await coding.click()
    assert.notEqual(await coding.getAttribute('aria-pressed'), before)
    await coding.click()
    assert.equal(await coding.getAttribute('aria-pressed'), before)
    assert.equal(await input.inputValue(), draft)
    assert((await page.getByTitle('Permissions mode', { exact: true }).textContent()).includes(label))
    await menu.press('Escape')
  }
  await mode.click()
  await page.getByRole('menu', { name: 'Working mode' }).getByRole('button', { name: /Plan before editing/ }).click()
  await page.waitForFunction(async id => (await window.api.plan.isModeActive(id)).data === true, ids[1])
  await page.getByRole('menu', { name: 'Working mode' }).press('Escape')
  await page.getByRole('button', { name: 'Exit & Execute', exact: true }).click()
  await page.waitForFunction(async id => (await window.api.plan.isModeActive(id)).data === false, ids[1])
  assert.notEqual((await mode.textContent()).trim(), 'Plan')
  assert.equal(await input.inputValue(), draft)
  const messagesBefore = await page.evaluate(async id => (await window.api.conversation.getMessages(id)).data.length, ids[1])
  const unhandled = await input.evaluate(element => element.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', code: 'Enter', bubbles: true, cancelable: true, isComposing: true })))
  assert.equal(unhandled, true)
  assert.equal(await input.inputValue(), draft)
  assert.equal(await page.evaluate(async id => (await window.api.conversation.getMessages(id)).data.length, ids[1]), messagesBefore)
  const code = Array.from({ length: 30 }, (_, index) => `const value${index} = ${index};`).join('\n')
  await input.evaluate((element, text) => {
    const clipboardData = new DataTransfer()
    clipboardData.setData('text/plain', text)
    element.dispatchEvent(new ClipboardEvent('paste', { clipboardData, bubbles: true, cancelable: true }))
  }, code)
  await page.getByRole('button', { name: 'Paste inline', exact: true }).click()
  assert((await input.inputValue()).includes(code))
  await input.fill(draft)
  await input.evaluate((element, text) => {
    const clipboardData = new DataTransfer()
    clipboardData.setData('text/plain', text)
    element.dispatchEvent(new ClipboardEvent('paste', { clipboardData, bubbles: true, cancelable: true }))
  }, code)
  await page.getByRole('button', { name: 'Paste as attachment', exact: true }).click()
  await page.getByTitle('Remove attachment', { exact: true }).waitFor()
  assert.equal(await input.inputValue(), draft)
  await page.getByTitle('Remove attachment', { exact: true }).click()
  const file = path.join(profile, 'composer-attachment.txt')
  fs.writeFileSync(file, 'Real picked attachment')
  await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }) }, file)
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('button', { name: /Add files or photos/ }).click()
  await page.getByText('composer-attachment.txt', { exact: true }).waitFor()
  assert.equal(await input.inputValue(), draft)
  await mode.click()
  await page.getByRole('menu', { name: 'Working mode' }).press('Escape')
  await page.getByText('composer-attachment.txt', { exact: true }).waitFor()
  await page.getByTitle('Remove attachment', { exact: true }).click()
  const after = await page.evaluate(async () => (await window.api.settings.get()).data)
  assert.equal(after.agenticCodingMode, settings.agenticCodingMode)
  assert.equal(requestCount(), requestsBefore)
  await input.fill('')
  return { textAndMultilinePaste: true, pasteAsAttachment: true, nativePickerFileProcessing: true, imeDidNotSubmit: true, permissionModes: 3, codingRestored: true, persistedPlanGate: true, draftPreservedAcrossModeChanges: true, providerRequestsDuringScenario: requestCount() - requestsBefore, boundaries: 'Synthetic clipboard/IME events and controlled native chooser; production renderer, preload, main, file processing, settings and plan storage.' }
}
