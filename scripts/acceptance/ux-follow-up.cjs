/* global window, document */
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

module.exports = async function followUpScenario({ page, app, ids, profile, requestCount, finishStreams, providerBodies }) {
  const owner = ids[1]
  const input = page.getByRole('textbox', { name: 'Message Lamprey', exact: true })
  const snapshot = () => page.evaluate(async id => { const r = await window.api.turn.getState(id); if (!r.success) throw new Error(r.error); return r.data }, owner)
  const choose = async mode => {
    await page.getByRole('button', { name: 'Choose Steer or Queue', exact: true }).click()
    await page.locator(`[data-follow-up-choice="${mode}"]`).click()
    await page.locator(`[data-follow-up-action="${mode}"]`).waitFor()
  }
  const queueCard = text => page.getByRole('article', { name: 'Queued follow-up', exact: true }).filter({ hasText: text })
  await input.fill('Start the UX follow-up fixture turn.')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.getByRole('button', { name: 'Stop current turn', exact: true }).waitFor()
  const active = (await snapshot()).activeTurn
  assert(active)
  const requestsBeforeMenu = requestCount()
  await input.fill('Queue first mixed draft')
  await page.getByRole('button', { name: 'Choose Steer or Queue', exact: true }).click()
  await page.getByRole('menu', { name: 'Follow-up action' }).press('ArrowDown')
  await page.getByRole('menu', { name: 'Follow-up action' }).press('Escape')
  assert.equal((await snapshot()).followUps.length, 0)
  assert.equal(requestCount(), requestsBeforeMenu)
  assert.equal(await input.inputValue(), 'Queue first mixed draft')
  await choose('queue')
  assert.equal((await snapshot()).followUps.length, 0)
  await app.evaluate(({ ipcMain }) => {
    const original = ipcMain._invokeHandlers.get('turn:queue')
    ipcMain.removeHandler('turn:queue')
    ipcMain.handle('turn:queue', async () => {
      ipcMain.removeHandler('turn:queue')
      ipcMain.handle('turn:queue', original)
      throw new Error('UX injected IPC failure')
    })
  })
  await page.locator('[data-follow-up-action="queue"]').click()
  await page.getByRole('alert').filter({ hasText: 'Your draft is still editable.' }).waitFor()
  assert.equal(await input.inputValue(), 'Queue first mixed draft')
  assert.equal((await snapshot()).followUps.length, 0)
  assert.equal(requestCount(), requestsBeforeMenu)
  await app.evaluate(({ dialog }, missing) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [missing] }) }, path.join(profile, 'unreadable-follow-up.txt'))
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('button', { name: /Add files or photos/ }).click()
  await page.getByText('unreadable-follow-up.txt', { exact: true }).waitFor()
  await page.locator('[data-follow-up-action="queue"]').click()
  await page.getByRole('alert').filter({ hasText: 'Your draft is still editable.' }).filter({ hasText: 'Could not read file' }).waitFor()
  assert.equal((await snapshot()).followUps.length, 0)
  assert.equal(await input.inputValue(), 'Queue first mixed draft')
  await page.getByTitle('Remove attachment', { exact: true }).click()
  const textFile = path.join(profile, 'follow-up-note.txt')
  const imageFile = path.join(profile, 'follow-up-image.png')
  fs.writeFileSync(textFile, 'Keep this attachment after the image.')
  fs.writeFileSync(imageFile, Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jRZkAAAAASUVORK5CYII=', 'base64'))
  await app.evaluate(({ dialog }, files) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: files }) }, [imageFile, textFile])
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('button', { name: /Add files or photos/ }).click()
  await page.getByText('follow-up-note.txt', { exact: true }).waitFor()
  await page.locator('[data-follow-up-action="queue"]').evaluate(button => { button.click(); button.click() })
  await queueCard('Queue first mixed draft').waitFor()
  let state = await snapshot()
  assert.equal(state.followUps.filter(f => f.status === 'queued').length, 1, 'Synchronous double submit creates one record')
  const first = state.followUps.find(f => f.status === 'queued')
  assert.deepEqual(first.input.map(item => item.type), ['text', 'image', 'text'])
  assert.equal(first.input[1].imageUrl, 'data:image/png;base64,' + fs.readFileSync(imageFile).toString('base64'))
  assert(first.input[2].text.includes('Keep this attachment'))
  await app.evaluate(({ ipcMain }) => {
    const original = ipcMain._invokeHandlers.get('turn:queue')
    ipcMain.removeHandler('turn:queue')
    ipcMain.handle('turn:queue', async (...args) => {
      ipcMain.removeHandler('turn:queue')
      ipcMain.handle('turn:queue', original)
      const result = await original(...args)
      await new Promise(resolve => { globalThis.uxReleaseQueue = resolve })
      return result
    })
  })
  await input.fill('Delayed acknowledgement draft')
  await page.locator('[data-follow-up-action="queue"]').click()
  await app.evaluate(async () => {
    for (let i = 0; i < 100 && !globalThis.uxReleaseQueue; i++) await new Promise(resolve => setTimeout(resolve, 20))
    if (!globalThis.uxReleaseQueue) throw new Error('Queue acknowledgement did not reach fixture boundary')
  })
  await input.fill('Newer draft must survive')
  await app.evaluate(() => { globalThis.uxReleaseQueue(); delete globalThis.uxReleaseQueue })
  await page.waitForFunction(() => !document.querySelector('[data-follow-up-action="queue"]').disabled)
  assert.equal(await input.inputValue(), 'Newer draft must survive')
  await queueCard('Delayed acknowledgement draft').getByRole('button', { name: 'Delete', exact: true }).click()
  await queueCard('Delayed acknowledgement draft').waitFor({ state: 'hidden' })
  await input.fill('Queue second draft')
  await page.locator('[data-follow-up-action="queue"]').click()
  await queueCard('Queue second draft').waitFor()
  await queueCard('Queue first mixed draft').getByRole('button', { name: 'Edit', exact: true }).click()
  await queueCard('Queue first mixed draft').getByRole('textbox', { name: 'Edit follow-up text' }).fill('Queue first edited')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await queueCard('Queue first edited').waitFor()
  await queueCard('Queue second draft').getByRole('button', { name: 'Move queued follow-up up' }).click()
  await page.waitForFunction(async id => {
    const q = (await window.api.turn.getState(id)).data.followUps.filter(f => f.status === 'queued').sort((a,b) => a.position-b.position)
    return q[0]?.input[0].text === 'Queue second draft'
  }, owner)
  await page.reload()
  await page.getByText('UX baseline task 01', { exact: true }).last().click()
  await queueCard('Queue first edited').waitFor()
  assert.equal((await page.evaluate(async () => (await window.api.settings.get()).data)).followUpBehavior, 'queue')
  state = await snapshot()
  assert.deepEqual(state.followUps.find(f => f.id === first.id).input.slice(1), first.input.slice(1))
  await queueCard('Queue second draft').getByRole('button', { name: 'Send now', exact: true }).click()
  await page.getByRole('article', { name: 'Steering follow-up pending delivery' }).filter({ hasText: 'Queue second draft' }).waitFor()
  await choose('steer')
  await input.fill('Steer at the real safe boundary')
  await page.locator('[data-follow-up-action="steer"]').click()
  await page.getByRole('article', { name: 'Steering follow-up pending delivery' }).filter({ hasText: 'Steer at the real safe boundary' }).waitFor()
  const stale = await page.evaluate(async ({ owner }) => window.api.turn.steer({ conversationId: owner, expectedTurnId: 'stale-turn', deliveryMode: 'steer', actor: 'user', clientUserMessageId: 'ux-stale', input: [{ type: 'text', text: 'Must reject stale target' }] }), { owner })
  assert.equal(stale.success, false)
  assert.equal(stale.rejection.reason, 'turnMismatch')
  const beforeBoundary = requestCount()
  finishStreams()
  await page.waitForFunction(async id => (await window.api.turn.getState(id)).data.followUps.filter(f => f.status === 'delivered').length >= 2, owner)
  await page.waitForFunction(() => document.querySelector('[aria-label="Stop current turn"]') !== null)
  for (let attempt = 0; attempt < 100 && !providerBodies.some(body => JSON.stringify(body.messages).includes('Steer at the real safe boundary')); attempt++) await new Promise(resolve => setTimeout(resolve, 50))
  assert(requestCount() > beforeBoundary)
  assert(providerBodies.some(body => JSON.stringify(body.messages).includes('Steer at the real safe boundary')))
  await queueCard('Queue first edited').getByRole('button', { name: 'Delete', exact: true }).click()
  await queueCard('Queue first edited').waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('button', { name: /Add files or photos/ }).click()
  await page.getByText('follow-up-note.txt', { exact: true }).waitFor()
  await input.fill('Recover this steering on cancellation')
  await page.locator('[data-follow-up-action="steer"]').click()
  await page.getByRole('article', { name: 'Steering follow-up pending delivery' }).filter({ hasText: 'Recover this steering on cancellation' }).waitFor()
  await page.getByRole('button', { name: 'Stop current turn', exact: true }).click()
  await page.getByRole('button', { name: 'Send', exact: true }).waitFor()
  await page.getByRole('article', { name: 'Recoverable follow-up draft', exact: true }).filter({ hasText: 'Recover this steering on cancellation' }).waitFor()
  await page.reload()
  await page.getByText('UX baseline task 01', { exact: true }).last().click()
  const recovered = page.getByRole('article', { name: 'Recoverable follow-up draft', exact: true }).filter({ hasText: 'Recover this steering on cancellation' })
  await recovered.waitFor()
  const recoveryInput = (await snapshot()).followUps.find(f => f.status === 'recovered' && f.input[0]?.text === 'Recover this steering on cancellation').input
  assert.deepEqual(recoveryInput.map(item => item.type), ['text', 'image', 'text'])
  await recovered.getByRole('button', { name: 'Queue draft', exact: true }).click()
  await queueCard('Recover this steering on cancellation').waitFor()
  assert.deepEqual((await snapshot()).followUps.find(f => f.status === 'queued' && f.input[0]?.text === 'Recover this steering on cancellation').input, recoveryInput)
  await queueCard('Recover this steering on cancellation').getByRole('button', { name: 'Delete', exact: true }).click()
  await input.fill('')
  return { primaryPreferenceMenuDoesNotSubmit: true, failedIpcPreservesDraft: true, unreadableAttachmentRejected: true, delayedAcknowledgementKeepsNewDraft: true, synchronousDoubleSubmit: 'one durable record', orderedMixedInput: first.input.map(item => item.type), editReorderReload: true, sendNowAndSteerDelivered: true, staleTurnRejected: stale.rejection.reason, explicitDelete: true, cancellationRecoveryAndReloadRetry: true, requests: requestCount(), activeTurn: active.turnId, boundaries: 'Real renderer/preload/main turn service, SQLite, file processing and loopback provider; native file chooser and IPC fault/acknowledgement boundaries controlled.' }
}
