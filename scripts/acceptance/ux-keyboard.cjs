/* global window, document, KeyboardEvent */
const assert = require('node:assert/strict')
module.exports = async function keyboardScenario({ page, app, ids, trackPid }) {
  page.on('pageerror', error => console.error('UX26 renderer error:', error.stack ?? error.message))
  const owner = ids[38]
  await page.reload()
  const primary = page.getByRole('complementary', { name: 'Task sidebar' })
  await primary.getByRole('button', { name: 'Recent', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Search tasks', exact: true }).fill('')
  await page.getByRole('combobox', { name: 'Filter tasks by project' }).selectOption('__all__')
  await page.locator(`[data-task-id="${owner}"]`).getByRole('button', { name: /^UX baseline/ }).first().click()
  const input = page.getByRole('textbox', { name: 'Message Lamprey', exact: true })
  await input.fill('UX26 keep this draft')
  const menu = page.getByRole('dialog', { name: 'Command menu', exact: true })
  for (const binding of ['Control+k', 'Control+Shift+p']) {
    await input.focus(); await page.keyboard.press(binding); await menu.waitFor(); await page.keyboard.press('Escape'); assert.equal(await menu.count(), 0)
  }
  await input.focus(); await page.keyboard.press('Control+Shift+m')
  await page.getByRole('menu', { name: 'Models', exact: true }).waitFor(); await page.keyboard.press('Escape')
  await input.focus(); await page.keyboard.press('Control+Alt+m')
  await page.getByRole('dialog', { name: 'Memory', exact: true }).waitFor(); await page.keyboard.press('Escape')
  await input.focus(); await page.keyboard.press('Control+,')
  const settings = page.getByRole('dialog', { name: 'Settings', exact: true }); await settings.waitFor()
  const count = await page.evaluate(async () => (await window.api.conversation.list()).data.length)
  await page.keyboard.press('Control+n'); await page.keyboard.press('Control+k')
  assert.equal(await menu.count(), 0); assert.equal(await page.evaluate(async () => (await window.api.conversation.list()).data.length), count)
  await page.keyboard.press('Escape'); assert.equal(await settings.count(), 0)
  await input.focus()
  const composition = await input.evaluate(element => element.dispatchEvent(new KeyboardEvent('keydown', { key: 'n', ctrlKey: true, isComposing: true, bubbles: true, cancelable: true })))
  assert(composition); assert.equal(await page.evaluate(async () => (await window.api.conversation.list()).data.length), count)
  const repeated = await input.evaluate(element => element.dispatchEvent(new KeyboardEvent('keydown', { key: 'n', ctrlKey: true, repeat: true, bubbles: true, cancelable: true })))
  assert(repeated)
  await page.keyboard.press('Control+b'); await page.getByRole('button', { name: 'Expand sidebar', exact: true }).waitFor()
  await input.focus(); await page.keyboard.press('Control+b'); await primary.getByRole('button', { name: 'Recent', exact: true }).waitFor()
  await input.focus(); await page.keyboard.press('Control+j')
  const dock = page.getByRole('region', { name: 'Terminal dock', exact: true })
  await dock.getByRole('status').getByText('Running', { exact: true }).waitFor()
  const id = `lamprey-task:${encodeURIComponent(owner)}:powershell`
  const snapshot = await page.evaluate(async id => (await window.api.terminal.snapshot({ id })).data, id); trackPid(snapshot.pid)
  await dock.locator('.xterm-helper-textarea').focus(); await page.keyboard.press('Control+k')
  assert.equal(await menu.count(), 0)
  await input.focus(); await page.keyboard.press('Control+j'); assert.equal(await dock.count(), 0)
  await page.keyboard.press('Control+`'); await dock.waitFor()
  await dock.getByRole('button', { name: 'Terminate shell' }).click(); await dock.getByRole('button', { name: 'Hide terminal' }).click()
  await input.focus(); await page.keyboard.press('Control+Shift+g'); await page.getByRole('tab', { name: 'Review', exact: true }).waitFor()
  await input.focus(); await page.keyboard.press('Control+p')
  const files = page.getByPlaceholder(/^Type a filename/); await files.waitFor()
  await files.fill('example'); await page.keyboard.press('Control+n')
  assert.equal(await page.evaluate(async () => (await window.api.conversation.list()).data.length), count)
  await page.keyboard.press('Escape')
  assert.equal(await input.inputValue(), 'UX26 keep this draft')
  await input.focus(); await page.keyboard.press('Control+k')
  await menu.getByRole('combobox').fill('Manage task worktrees'); await menu.locator('[data-command-id="app.worktrees"]').click()
  await page.getByRole('dialog', { name: 'Worktrees' }).waitFor(); await page.keyboard.press('Escape'); assert.equal(await page.getByRole('dialog', { name: 'Worktrees' }).count(), 0)
  await page.getByRole('button', { name: 'Add', exact: true }).click()
  await page.getByRole('button', { name: 'Keyboard help', exact: true }).click()
  const help = page.getByRole('dialog', { name: 'Composer keyboard help' }); await help.waitFor()
  assert((await help.innerText()).includes('Ctrl/Cmd+Alt+M')); assert((await help.innerText()).includes('Ctrl/Cmd+Shift+P'))
  await page.keyboard.press('Escape')
  await input.focus(); await page.keyboard.press('Control+k')
  const browserTab = await page.evaluate(async ownerId => (await window.api.browser.newTab({ ownerId, url: 'about:blank' })).data.id, owner)
  await menu.getByRole('combobox').fill('Browser'); await menu.locator('[data-command-id="tool.browser"]').click()
  const address = page.getByPlaceholder('Search Google or type a URL'); await address.waitFor(); await page.waitForFunction(() => !document.querySelector('input[placeholder="Search Google or type a URL"]')?.disabled); await address.focus(); assert(await address.evaluate(element => document.activeElement === element)); await page.keyboard.press('Control+n')
  assert.equal(await page.evaluate(async () => (await window.api.conversation.list()).data.length), count)
  await page.evaluate(id => window.api.browser.closeTab({ id }), browserTab)
  await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.setContentSize(800, 600); win.webContents.setZoomFactor(2) })
  await input.focus(); await page.keyboard.press('Control+Shift+p'); await menu.waitFor(); await page.keyboard.press('Escape')
  assert.equal(await menu.count(), 0)
  await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.webContents.setZoomFactor(1); win.setContentSize(1440, 900) })
  await input.focus(); await page.keyboard.press('Control+n')
  await page.waitForFunction(async count => (await window.api.conversation.list()).data.length === count + 1, count)
  assert.equal(await input.inputValue(), '')
  await input.focus(); await page.keyboard.press('Control+k'); await menu.waitFor(); await menu.getByRole('button', { name: 'Tasks', exact: true }).click(); await menu.getByRole('option', { name: /Untitled task/ }).waitFor(); await page.keyboard.press('Escape')
  const viewportChecks = []
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const theme of ['Light', 'Dark']) {
    await input.focus(); await page.keyboard.press('Control+,')
    await settings.getByRole('button', { name: 'Appearance', exact: true }).click()
    await settings.getByRole('button', { name: theme, exact: true }).click(); await page.keyboard.press('Escape')
    for (const [width, height] of [[1440, 900], [1024, 768], [800, 600], [1920, 1080]]) for (const zoom of [1, 1.5, 2]) {
      await app.evaluate(({ BrowserWindow }, { width, height, zoom }) => { const win = BrowserWindow.getAllWindows()[0]; win.setContentSize(width, height); win.webContents.setZoomFactor(zoom) }, { width, height, zoom })
      await input.focus(); await page.keyboard.press('Control+k'); await menu.waitFor()
      const geometry = await menu.evaluate(element => { const rect = element.getBoundingClientRect(); const results = element.querySelector('[role="listbox"]'); return { width: window.innerWidth, height: window.innerHeight, left: rect.left, right: rect.right, top: rect.top, bottom: rect.bottom, resultsHeight: results.getBoundingClientRect().height, focused: element.contains(document.activeElement) } })
      assert(geometry.focused); assert(geometry.left >= 0 && geometry.right <= geometry.width + 1); assert(geometry.top >= 0 && geometry.bottom <= geometry.height + 1); assert(geometry.resultsHeight > 0)
      await page.keyboard.press('Escape'); await menu.waitFor({ state: 'hidden' })
      assert(await input.evaluate(element => document.activeElement === element))
      viewportChecks.push({ theme, width, height, zoom, geometry })
    }
    await app.evaluate(({ BrowserWindow }) => { const win = BrowserWindow.getAllWindows()[0]; win.webContents.setZoomFactor(1); win.setContentSize(1440, 900) })
  }
  return { viewportChecks, commandAliases: true, modelAndMemoryBindings: true, modalOwnership: true, compositionAndRepeatIgnored: true, sidebarAndTerminalBindings: true, terminalInputOwnership: true, reviewAndFiles: true, fileInputOwnership: true, browserInputOwnership: true, narrowZoomKeyboard: true, worktreeEscape: true, helpUsesMetadata: true, newTaskOnce: true, previousDraftRetained: true }
}
