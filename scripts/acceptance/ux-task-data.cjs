/* global window, document, getComputedStyle */
const assert = require('node:assert/strict')
module.exports = async function taskDataScenario({ page, ids, repo }) {
  const result = await page.evaluate(async ({ owner, repo }) => {
    const project = await window.api.projects.create({ name: 'UX21 project relationship', path: repo })
    if (!project.success) throw new Error(project.error)
    const assigned = await window.api.projects.assignConversation(owner, project.data.id)
    if (!assigned.success) throw new Error(assigned.error)
    const pinned = await window.api.sessions.setPinned(owner, true)
    if (!pinned.success) throw new Error(pinned.error)
    const fork = await window.api.conversation.fork(owner)
    if (!fork.success) throw new Error(fork.error)
    const archived = await window.api.sessions.archive(owner, true)
    if (!archived.success) throw new Error(archived.error)
    return { owner, projectId: project.data.id, forkId: fork.data.conversationId }
  }, { owner: ids[29], repo })
  await page.reload()
  const rows = await page.evaluate(async ids => ({
    conversations: (await window.api.conversation.list()).data,
    archived: (await window.api.sessions.list({ tab: 'archived' })).data,
    pinned: (await window.api.sessions.list({ tab: 'pinned' })).data,
    lineage: (await window.api.conversation.lineage(ids.forkId)).data,
    projects: (await window.api.projects.list()).data
  }), result)
  const task = rows.conversations.find(row => row.id === result.owner)
  const archived = rows.archived.find(row => row.id === result.owner)
  const fork = rows.conversations.find(row => row.id === result.forkId)
  assert(task && archived && fork)
  assert.equal(task.projectId, result.projectId)
  assert.equal(archived.projectId, result.projectId)
  assert.equal(task.archived, true)
  assert.equal(archived.pinnedAt, task.pinnedAt)
  assert.equal(fork.forkedFromId, result.owner)
  assert.equal(fork.projectId, result.projectId)
  assert.equal(new Set(rows.conversations.map(row => row.id)).size, rows.conversations.length)
  assert(rows.projects.some(row => row.id === result.projectId))
  await page.getByRole('button', { name: 'Archived', exact: true }).click()
  const panel = page.getByTestId('sessions-sidebar')
  await panel.getByText('UX21 project relationship', { exact: true }).waitFor()
  await panel.getByTitle(task.title, { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Recent', exact: true }).click()
  const primary = page.getByRole('complementary', { name: 'Task sidebar' })
  const existing = await page.evaluate(async () => (await window.api.conversation.list()).data.map(row => row.id))
  await primary.getByRole('button', { name: 'New task', exact: true }).click()
  await page.waitForFunction(async before => (await window.api.conversation.list()).data.some(row => !before.includes(row.id)), existing)
  const created = await page.evaluate(async before => (await window.api.conversation.list()).data.find(row => !before.includes(row.id)), existing)
  const row = page.locator(`[data-task-id="${created.id}"]`)
  await row.waitFor()
  await row.getByRole('button', { name: /^Task actions:/ }).click()
  await page.getByRole('menuitem', { name: 'Rename', exact: true }).click()
  await page.getByRole('textbox', { name: 'Rename task', exact: true }).fill('UX22 renamed task')
  await page.getByRole('textbox', { name: 'Rename task', exact: true }).press('Enter')
  await row.getByTitle('UX22 renamed task', { exact: true }).waitFor()
  await row.getByTitle('Pin', { exact: true }).click()
  await primary.getByRole('button', { name: 'Pinned', exact: true }).click()
  await row.getByTitle('Unpin', { exact: true }).waitFor()
  await row.getByTitle('Unpin', { exact: true }).click()
  await primary.getByRole('button', { name: 'Recent', exact: true }).click()
  await row.getByRole('button', { name: /^Task actions:/ }).click()
  await page.getByRole('menuitem', { name: 'Archive', exact: true }).click()
  await primary.getByRole('button', { name: 'Archived', exact: true }).click()
  await row.getByRole('button', { name: /^Task actions:/ }).click()
  await page.getByRole('menuitem', { name: 'Unarchive', exact: true }).click()
  await primary.getByRole('button', { name: 'Recent', exact: true }).click()
  await row.getByRole('button', { name: /^Task actions:/ }).click()
  await page.getByRole('menuitem', { name: 'Fork task', exact: true }).click()
  await page.waitForFunction(async owner => (await window.api.conversation.list()).data.some(row => row.forkedFromId === owner), created.id)
  const projectRow = page.locator(`[data-project-id="${result.projectId}"]`)
  await projectRow.getByTitle('UX21 project relationship', { exact: true }).click()
  await page.getByRole('dialog', { name: 'UX21 project relationship', exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await projectRow.getByRole('button', { name: /^Project actions:/ }).click()
  await page.getByRole('menuitem', { name: 'Manage worktrees', exact: true }).click()
  await page.getByRole('dialog', { name: 'Worktrees', exact: true }).waitFor()
  await page.getByRole('dialog', { name: 'Worktrees', exact: true }).getByText(repo.replaceAll('\\', '/'), { exact: true }).waitFor()
  await page.getByRole('dialog', { name: 'Worktrees', exact: true }).getByRole('button', { name: 'Close', exact: true }).click()
  await projectRow.getByRole('button', { name: /^Project actions:/ }).click()
  await page.getByRole('menuitem', { name: 'Rename project', exact: true }).click()
  const longName = 'UX22 long project name '.repeat(8)
  await page.getByRole('textbox', { name: 'Rename project', exact: true }).fill(longName)
  await page.getByRole('textbox', { name: 'Rename project', exact: true }).press('Enter')
  const projectButton = projectRow.getByTitle(longName.trim(), { exact: true })
  await projectButton.waitFor()
  assert(await projectButton.evaluate(node => node.scrollWidth > node.clientWidth && getComputedStyle(node).textOverflow === 'ellipsis'))
  await row.getByTitle('UX22 renamed task', { exact: true }).focus()
  await page.keyboard.press('Enter')
  await page.waitForFunction(id => document.querySelector(`[data-task-id="${id}"] [aria-current="page"]`), created.id)
  assert(await row.evaluate(node => { const list = node.closest('[role="listbox"]'); const a = node.getBoundingClientRect(); const b = list.getBoundingClientRect(); return a.top >= b.top && a.bottom <= b.bottom }))
  await primary.getByRole('button', { name: 'Collapse sidebar', exact: true }).click()
  await primary.getByRole('button', { name: 'Search', exact: true }).click()
  await page.getByRole('searchbox', { name: 'Search tasks', exact: true }).waitFor()
  assert(await page.getByRole('searchbox', { name: 'Search tasks', exact: true }).evaluate(node => node === document.activeElement))
  return { primaryTaskActions: ['new', 'rename', 'pin', 'unpin', 'archive', 'unarchive', 'fork'], projectSelection: true, longProjectNameTruncationWithFullTitle: true, selectedTaskRevealed: true, keyboardTaskSelection: true, projectOwnedWorktrees: true, collapsedSearchKeyboardFocus: true, realProjectAssignment: true, archivedAndPinnedMetadataSurvivesReload: true, forkLineageAndProjectPreserved: true, sameIdentityAcrossProjections: true, archivedTaskDiscoverable: true }
}
